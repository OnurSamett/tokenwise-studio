const isTurkishLocale = (loc) => /^tr(?=$|[-_])/i.test(String(loc || "").trim());

/** Resolve "auto" | "en" | "tr" to "en" or "tr". Works in both browser and Node. */
export function resolveLanguage(setting = "auto", { navigatorLang, env, intlLocale } = {}) {
  if (setting === "tr" || setting === "en") return setting;
  const inBrowser = typeof document !== "undefined";
  let loc = navigatorLang !== undefined
    ? navigatorLang
    : (inBrowser && typeof navigator !== "undefined" ? (navigator.languages?.[0] || navigator.language) : "");
  if (!loc && (env !== undefined || !inBrowser)) {
    const e = env || (typeof process !== "undefined" ? process.env : {});
    loc = e?.LC_ALL || e?.LC_MESSAGES || e?.LANG || "";
  }
  if (!loc && !inBrowser && navigatorLang === undefined && env === undefined && typeof navigator !== "undefined") {
    loc = navigator.languages?.[0] || navigator.language || "";
  }
  if (!loc) {
    try { loc = intlLocale !== undefined ? intlLocale : Intl.DateTimeFormat().resolvedOptions().locale; } catch {}
  }
  return isTurkishLocale(loc) ? "tr" : "en";
}

export const hasKey = (key, lang = "en") => Object.hasOwn(DICT[lang] || DICT.en, key);

export function t(key, vars = {}, lang = "en") {
  const table = DICT[lang] || DICT.en;
  const raw = Object.hasOwn(table, key) ? table[key] : (Object.hasOwn(DICT.en, key) ? DICT.en[key] : key);
  if (!vars || typeof raw !== "string") return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : ""));
}

export const tp = (key, n, vars = {}, lang = "en") => t(`${key}.${n === 1 ? "one" : "other"}`, { n, ...vars }, lang);

/** Localize known backend limit/handoff reason strings without modifying log formats. */
export function translateReason(reason, lang = "en") {
  const s = String(reason || "");
  if (!s || lang !== "tr") return s;
  let m;
  if ((m = s.match(/^(\w+) not available$/i))) return t("reason.agentNotAvailable", { agent: m[1] }, lang);
  const cm = s.match(/^(Claude)\s+(.+)$/i);
  const prefix = cm ? `${cm[1]} ` : "";
  const body = cm ? cm[2] : s;
  if ((m = body.match(/^5-hour limit at (\d+)%$/i))) return prefix + t("reason.fiveHourLimit", { pct: m[1] }, lang);
  if ((m = body.match(/^weekly limit at (\d+)%$/i))) return prefix + t("reason.weeklyLimit", { pct: m[1] }, lang);
  if (/^is not available$/i.test(body)) return prefix ? `${cm[1]} ${t("reason.unavailable", {}, lang)}` : t("reason.unavailable", {}, lang);
  if (/^is unavailable$|^unavailable$/i.test(body)) return prefix + t("reason.unavailable", {}, lang);
  if (/^hit its usage limit$/i.test(body)) return prefix + t("reason.usageLimit", {}, lang);
  if (/^hit a rate limit$/i.test(body)) return prefix + t("reason.rateLimit", {}, lang);
  if (/^chosen by user$/i.test(body)) return t("reason.chosenByUser", {}, lang);
  if (/^forced by TOKENWISE_ORCH_FORCE$/i.test(body)) return t("reason.forced", {}, lang);
  return s;
}

/** Localize known orchestrator notice strings stored in chat logs. */
export function translateNotice(text, lang = "en") {
  const s = String(text || "");
  if (!s || lang !== "tr") return s;
  let m;
  if ((m = s.match(/^Turn budget reached \((.+?) of (.+?) tokens\)\./))) {
    return t("notice.budgetReached", { used: m[1], budget: m[2] }, lang);
  }
  if ((m = s.match(/^Turn budget at (\d+)% \((.+?) of (.+?) tokens\)\./))) {
    return t("notice.budgetWarn", { pct: m[1], used: m[2], budget: m[3] }, lang);
  }
  return s;
}
